import { ArrowLeft, ArrowUpRight } from "lucide-react";
import type { MouseEvent, ReactNode } from "react";
import { KeepsakeWordmark } from "../components/KeepsakeMark";

/**
 * Legal pages are deliberately standalone: they render before the auth gate so
 * the Terms and Privacy Policy are reachable without an account (a privacy
 * policy URL is required for Google OAuth verification, and a person should be
 * able to read what they agree to before signing up). They carry their own
 * minimal header instead of the app's navigation rail.
 */

const CONTACT = "kuskomanass@gmail.com";
const LAST_UPDATED = "November 13, 2026";

function Section({ id, title, children }: { id: string; title: string; children: ReactNode }) {
  return (
    <section className="legal-section" id={id}>
      <h2>{title}</h2>
      {children}
    </section>
  );
}

function LegalShell({
  navigate,
  title,
  lede,
  updated,
  children,
}: {
  navigate: (path: string) => void;
  title: string;
  lede: string;
  updated: string;
  children: ReactNode;
}) {
  const link = (path: string) => (event: MouseEvent) => {
    event.preventDefault();
    navigate(path);
  };

  return (
    <div className="legal-page">
      <header className="legal-bar">
        <button className="legal-home" onClick={() => navigate("/")} aria-label="Keepsake home">
          <KeepsakeWordmark />
        </button>
        <button className="legal-back" onClick={() => navigate("/")}>
          <ArrowLeft size={14} /> Back to Keepsake
        </button>
      </header>

      <main className="legal-body">
        <p className="eyebrow">Legal</p>
        <h1 className="display">{title}</h1>
        <p className="legal-lede">{lede}</p>
        <p className="legal-updated">Last updated {updated}</p>

        {children}

        <footer className="legal-foot">
          <a href="/tos" onClick={link("/tos")}>
            Terms of Service
          </a>
          <a href="/pp" onClick={link("/pp")}>
            Privacy Policy
          </a>
          <a href={`mailto:${CONTACT}`}>
            {CONTACT} <ArrowUpRight size={13} />
          </a>
        </footer>
      </main>
    </div>
  );
}

